#!/usr/bin/env python3
"""Generate the Flutter design tokens from design/tokens.json.

    python3 tools/gen_tokens.py          # write shell/packages/aether_design/lib/src/tokens.g.dart
    python3 tools/gen_tokens.py --check  # exit 1 if the generated file is out of date (CI)

design/tokens.json is exported from the AetherOS design system. Never edit the
generated Dart file by hand: change the tokens, then run this script.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "design" / "tokens.json"
TARGET = ROOT / "shell" / "packages" / "aether_design" / "lib" / "src" / "tokens.g.dart"

# Dart words that cannot (or should not) be field names.
RESERVED = {"on", "in", "is", "as", "default", "new", "class", "switch", "case"}
CSS_GENERIC = {"-apple-system", "system-ui", "sans-serif", "serif", "monospace", "ui-monospace"}
APPLE_ONLY = {"SF Pro Display", "SF Pro Text", "SF Mono"}


def camel(name: str) -> str:
    head, *rest = re.split(r"[-_.]", name)
    out = head + "".join(part[:1].upper() + part[1:] for part in rest)
    return out + "State" if out in RESERVED else out


def px(value: str | int | float) -> float:
    if isinstance(value, (int, float)):
        return float(value)
    match = re.fullmatch(r"(-?[\d.]+)(px)?", value.strip())
    if not match:
        raise ValueError(f"only px lengths are supported, got {value!r}")
    return float(match.group(1))


def em(value: str, font_size: float) -> float:
    value = value.strip()
    if value.endswith("em"):
        return float(value[:-2]) * font_size
    return px(value)


def color(value: str) -> str:
    value = value.strip().lower()
    if value.startswith("#"):
        hexpart = value[1:]
        if len(hexpart) in (3, 4):
            hexpart = "".join(ch * 2 for ch in hexpart)
        if len(hexpart) == 6:
            hexpart += "ff"
        rgb, alpha = hexpart[:6], hexpart[6:]
        return f"Color(0x{alpha.upper()}{rgb.upper()})"
    match = re.fullmatch(r"rgba?\(\s*([\d.]+)\s*,\s*([\d.]+)\s*,\s*([\d.]+)\s*(?:,\s*([\d.]+)\s*)?\)", value)
    if match:
        r, g, b = (int(float(match.group(i))) for i in (1, 2, 3))
        a = round(float(match.group(4) or 1) * 255)
        return f"Color(0x{a:02X}{r:02X}{g:02X}{b:02X})"
    raise ValueError(f"unsupported colour {value!r}")


def num(value: float) -> str:
    text = f"{value:.4f}".rstrip("0").rstrip(".")
    return text if "." in text else text + ".0"


def generate(tokens: dict) -> str:
    themes = [theme["id"] for theme in tokens["color"]["themes"]]
    colors = tokens["color"]["tokens"]
    names = [camel(token["name"]) for token in colors]

    def value_for(token: dict, theme: str) -> str:
        value = token["value"]
        if isinstance(value, str):
            return color(value)
        return color(value.get(theme, value[themes[0]]))

    lines: list[str] = [
        "// GENERATED by tools/gen_tokens.py from design/tokens.json. Do not edit by hand.",
        "// ignore_for_file: public_member_api_docs",
        "",
        "import 'package:flutter/material.dart';",
        "",
    ]

    # Colours as a ThemeExtension, one const instance per theme.
    lines += ["@immutable", "class AetherColors extends ThemeExtension<AetherColors> {", "  const AetherColors({"]
    lines += [f"    required this.{name}," for name in names]
    lines += ["  });", ""]
    for token, name in zip(colors, names):
        lines.append(f"  /// {token.get('usage', '')}".rstrip())
        lines.append(f"  final Color {name};")
        lines.append("")
    for theme in themes:
        lines.append(f"  static const AetherColors {camel(theme)} = AetherColors(")
        lines += [f"    {name}: {value_for(token, theme)}," for token, name in zip(colors, names)]
        lines += ["  );", ""]
    lines += ["  @override", "  AetherColors copyWith({"]
    lines += [f"    Color? {name}," for name in names]
    lines += ["  }) {", "    return AetherColors("]
    lines += [f"      {name}: {name} ?? this.{name}," for name in names]
    lines += ["    );", "  }", ""]
    lines += [
        "  @override",
        "  AetherColors lerp(covariant ThemeExtension<AetherColors>? other, double t) {",
        "    if (other is! AetherColors) return this;",
        "    return AetherColors(",
    ]
    lines += [f"      {name}: Color.lerp({name}, other.{name}, t)!," for name in names]
    lines += ["    );", "  }", "}", ""]

    # Font family: the platform font on Apple devices, the first open family elsewhere.
    families = tokens["type"]["families"]
    lines += ["abstract final class AetherFonts {"]
    for key, stack in families.items():
        parts = [part.strip().strip('"') for part in stack.split(",")]
        portable = [part for part in parts if part not in CSS_GENERIC and part not in APPLE_ONLY]
        fallback = ", ".join(f"'{part}'" for part in portable)
        lines.append(f"  /// CSS stack: {stack}")
        lines.append(f"  static const List<String> {camel(key)}Fallback = <String>[{fallback}];")
    lines += ["}", ""]

    # Text styles, without a family: AetherTheme applies the platform family.
    lines += ["abstract final class AetherText {"]
    for group in tokens["type"]["groups"]:
        lines.append(f"  // {group['name']}")
        for style in group["styles"]:
            size = px(style["fontSize"])
            args = [f"fontSize: {num(size)}"]
            if "lineHeight" in style:
                lh = style["lineHeight"]
                ratio = float(lh) if isinstance(lh, (int, float)) and float(lh) < 10 else px(lh) / size
                args.append(f"height: {num(ratio)}")
            if "fontWeight" in style:
                args.append(f"fontWeight: FontWeight.w{int(style['fontWeight'])}")
            if "letterSpacing" in style:
                args.append(f"letterSpacing: {num(em(style['letterSpacing'], size))}")
            if style.get("usage"):
                lines.append(f"  /// {style['usage']}")
            lines.append(f"  static const TextStyle {camel(style['name'])} = TextStyle({', '.join(args)});")
    lines += ["}", ""]

    for family, cls in (("spacing", "AetherSpace"), ("radius", "AetherRadius")):
        lines.append(f"abstract final class {cls} {{")
        for token in tokens.get(family, {}).get("tokens", []):
            if token.get("usage"):
                lines.append(f"  /// {token['usage']}")
            lines.append(f"  static const double {camel(token['name'])} = {num(px(token['value']))};")
        lines += ["}", ""]

    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    output = generate(json.loads(SOURCE.read_text()))
    if "--check" in sys.argv:
        if not TARGET.exists() or TARGET.read_text() != output:
            print(f"{TARGET.relative_to(ROOT)} is out of date. Run: python3 tools/gen_tokens.py")
            return 1
        print("tokens up to date")
        return 0
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(output)
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
